// Regenerates docs/questionnaires/*.md from js/data/questions.js (source of truth).
// Run from repo root: node tools/gen-questionnaires.mjs   (CI fails if output is stale)
import { writeFileSync, mkdirSync } from 'node:fs';
import { CHAPTERS, QUICK_PULSE_IDS, QUESTIONS, RESONANCE_OPTIONS } from '../js/data/questions.js';
import { ALL_NODES_MAP } from '../js/data/nodes.js';

const OUT = 'docs/questionnaires';
const nodeName = id => ALL_NODES_MAP[id]?.label || id;

function answerKey() {
  const rows = RESONANCE_OPTIONS.map(o => `| ${o.label} | ${o.sublabel} |`).join('\n');
  return `## Answer options (every question)\n\n| Answer | Meaning |\n|---|---|\n${rows}\n\n` +
    `Questions marked **Direction** also ask who does what (shown only if the answer is not Neutral or Hard Limit).\n`;
}

function questionBlock(q, n) {
  const weights = Object.entries(q.weights)
    .sort((a, b) => b[1] - a[1])
    .map(([id, f]) => `${nodeName(id)} ×${f}`).join(' · ');
  const dir = q.hasPolarity ? `\n- **Direction:** ${q.polarityLabels.join(' / ')}` : '\n- **Direction:** not asked';
  return `### ${n}. ${q.tag}  \`${q.id}\`\n\n> ${q.scenario}\n\n**${q.prompt}**\n${dir}\n- **Feeds:** ${weights}\n`;
}

function build(title, intro, questions) {
  let md = `# ${title}\n\n<!-- Generated by tools/gen-questionnaires.mjs from js/data/questions.js. Edit the data, not this file. -->\n\n${intro}\n\n${answerKey()}\n`;
  let n = 0;
  for (const ch of CHAPTERS) {
    const qs = questions.filter(q => q.chapter === ch.id);
    if (!qs.length) continue;
    md += `\n## ${ch.title}\n\n_${ch.subtitle}_\n\n`;
    md += qs.map(q => questionBlock(q, ++n)).join('\n');
  }
  return md;
}

mkdirSync(OUT, { recursive: true });
const quick = QUESTIONS.filter(q => QUICK_PULSE_IDS.includes(q.id));
writeFileSync(`${OUT}/quick-pulse.md`, build(
  `KINKSYS — Quick Pulse (${quick.length} questions)`,
  'Short track, about 2 minutes. High-signal snapshot across drivers, key pathways and nervous-system baseline.',
  quick));
writeFileSync(`${OUT}/full-deep-dive.md`, build(
  `KINKSYS — Full Deep Dive (${QUESTIONS.length} questions)`,
  'Long track across 4 chapters. Questions also in the Quick Pulse are marked ⚡.',
  QUESTIONS.map(q => QUICK_PULSE_IDS.includes(q.id) ? { ...q, tag: `${q.tag} ⚡` } : q)));
console.log(`wrote ${OUT}/quick-pulse.md (${quick.length}) and ${OUT}/full-deep-dive.md (${QUESTIONS.length})`);
